"""
Render aws/plateletiq-aws.yaml from template.src.yaml and the Lambda sources.

The Lambda code lives in aws/lambdas/*.py so it can be read, linted and unit
tested like any other Python. CloudFormation's inline ``ZipFile`` lets the
whole stack deploy from a single uploaded file in the AWS console — no S3
bucket, no SAM CLI — as long as each function stays under 4,096 characters,
which this script enforces.

    python aws/build.py          # write the template
    python aws/build.py --check  # CI: fail if the committed template is stale
"""

import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
LIMIT = 4096
INDENT = " " * 10  # under "        ZipFile: |"

SOURCES = {
    "__LEDGER_CODE__": HERE / "lambdas" / "custody_ledger.py",
    "__REPORT_CODE__": HERE / "lambdas" / "compliance_report.py",
}


def render() -> str:
    template = (HERE / "template.src.yaml").read_text()
    for marker, path in SOURCES.items():
        code = path.read_text().rstrip("\n")
        if len(code) > LIMIT:
            raise SystemExit(f"{path.name} is {len(code)} characters; inline Lambda code must be <= {LIMIT}.")
        block = "\n".join((INDENT + line) if line else "" for line in code.splitlines())
        template = template.replace(marker, block)
    header = "# GENERATED by aws/build.py from template.src.yaml + aws/lambdas/*.py - do not edit by hand.\n"
    return header + template


def main() -> None:
    output = HERE / "plateletiq-aws.yaml"
    rendered = render()
    if "--check" in sys.argv:
        if not output.exists() or output.read_text() != rendered:
            raise SystemExit("aws/plateletiq-aws.yaml is out of date. Run: python aws/build.py")
        print("aws/plateletiq-aws.yaml is up to date.")
        return
    output.write_text(rendered)
    print(f"Wrote {output.relative_to(HERE.parent)}")


if __name__ == "__main__":
    main()
